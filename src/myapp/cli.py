import argparse
import json
import os
import shutil

# Development-only hook installer; no shell execution.
import subprocess  # nosec B404
from pathlib import Path

from myapp.core.config import Settings


def init_project() -> None:
    from myapp.core.environment import environment_example

    # Both deployment environment and an existing .env are checked before writing anything.
    if os.environ.get("APP_ENVIRONMENT", "").lower() == "production":
        raise SystemExit("project-init is development-only")
    settings = Settings()
    if settings.environment == "production":
        raise SystemExit("project-init is development-only")
    if Path(".env.example").read_text(encoding="utf-8") != environment_example():
        raise SystemExit(".env.example is stale: run uv run project-env")
    env = Path(".env")
    if not env.exists():
        with env.open("x", encoding="utf-8") as target:
            target.write(Path(".env.example").read_text(encoding="utf-8"))
        env.chmod(0o600)
    for name in (".local", ".local/contracts", ".local/tmp"):
        Path(name).mkdir(parents=True, exist_ok=True)
    Settings()  # Validate the resulting env, never print its values.
    if Path(".git").exists():
        executable = shutil.which("pre-commit")
        if not executable:
            raise SystemExit("pre-commit missing: run uv sync")
        # Only replace legacy hooks installed by this template, never unrelated hooks.
        for hook in ("pre-commit", "pre-push"):
            candidate = Path(".git/hooks") / hook
            if candidate.is_file() and "lefthook" in candidate.read_text(encoding="utf-8"):
                candidate.unlink()
        subprocess.run([executable, "install", "--install-hooks"], check=True)  # nosec B603
    print("Development environment initialized; existing .env preserved.")


def export_openapi() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--output", default="contracts/openapi.json")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    from myapp.main import create_app

    path = Path(args.output)
    path.parent.mkdir(parents=True, exist_ok=True)
    # Deterministic declaration defaults: runtime .env cannot change the frontend contract.
    schema = create_app(Settings.model_construct()).openapi()
    schema["x-generated"] = "Generated by export-openapi; do not edit"
    content = json.dumps(schema, indent=2, sort_keys=True, ensure_ascii=False) + "\n"
    if args.check:
        if not path.exists() or path.read_text(encoding="utf-8") != content:
            raise SystemExit("OpenAPI is stale: run uv run export-openapi")
        print("OpenAPI is current")
        return
    path.write_text(content, encoding="utf-8")
    print(f"OpenAPI exported to {path}")


def make_migration() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("message")
    args = parser.parse_args()
    from alembic import command
    from alembic.config import Config

    command.revision(Config("alembic.ini"), message=args.message, autogenerate=True)


def export_environment() -> None:
    from myapp.core.environment import environment_example

    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    content = environment_example()
    path = Path(".env.example")
    if args.check:
        if not path.exists() or path.read_text(encoding="utf-8") != content:
            raise SystemExit(".env.example is stale: run uv run project-env")
        return
    path.write_text(content, encoding="utf-8")
